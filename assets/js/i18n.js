let MK_LANG = localStorage.getItem('mk_lang') || 'vi';
function t(key){ return (I18N[MK_LANG] && I18N[MK_LANG][key]) || I18N.vi[key] || key; }
function setLang(l){
  MK_LANG = l; localStorage.setItem('mk_lang', l);
  document.documentElement.lang = l;
  applyI18n();
  document.dispatchEvent(new CustomEvent('mk:lang'));
}
function applyI18n(root){
  (root||document).querySelectorAll('[data-i18n]').forEach(el=>{ el.textContent = t(el.dataset.i18n); });
  (root||document).querySelectorAll('[data-i18n-ph]').forEach(el=>{ el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('.mk-lang button').forEach(b=>b.classList.toggle('on', b.dataset.lang===MK_LANG));
}
